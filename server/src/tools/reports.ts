import { z } from 'zod';
import { registry } from '../mcp/registry.js';
import { db } from '../db/index.js';

// --- handoff_summary ---
registry.registerTool({
  name: 'handoff_summary',
  description: 'Generate a short text summary of the last 24 hours for caregiver handoff',
  schema: z.object({}),
  roles: ['primary', 'family', 'aide'],
  handler: async (input, ctx) => {
    const since = new Date(new Date(ctx.now).getTime() - 24 * 3600000).toISOString();
    
    // Get meds given
    const meds = db.prepare(`
      SELECT m.name, COUNT(e.id) as count
      FROM med_events e JOIN medications m ON e.medication_id = m.id
      WHERE e.event_at >= ? AND e.status = 'given'
      GROUP BY m.name
    `).all(since) as any[];

    // Get observations
    const obs = db.prepare(`
      SELECT category, COUNT(id) as count
      FROM observations
      WHERE recorded_at >= ?
      GROUP BY category
    `).all(since) as any[];

    let summary = `In the last 24 hours, `;
    if (meds.length > 0) {
      summary += `meds given: ` + meds.map(m => `${m.count} ${m.name}`).join(', ') + `. `;
    } else {
      summary += `no meds recorded. `;
    }

    if (obs.length > 0) {
      summary += `Notes logged for: ` + obs.map(o => o.category).join(', ') + `.`;
    }

    return {
      safetyLevel: 'none',
      safetyCode: null,
      spokenText: summary,
      data: { summary, meds, obs }
    };
  }
});

// --- visit_export ---
registry.registerTool({
  name: 'visit_export',
  description: 'Generate a Markdown document of the last 7 days for a doctor visit',
  schema: z.object({
    daysBack: z.number().min(1).max(30).default(7)
  }),
  roles: ['primary', 'family', 'aide'],
  handler: async (input, ctx) => {
    const since = new Date(new Date(ctx.now).getTime() - input.daysBack * 24 * 3600000).toISOString();
    
    // Fetch circle for name
    const circle = db.prepare(`SELECT recipient_name FROM care_circles WHERE id = ?`).get(ctx.circleId) as any;
    const name = circle ? circle.recipient_name : 'Patient';

    let md = `# Care Log: ${name}\n`;
    md += `*Generated on ${new Date(ctx.now).toISOString().substring(0, 10)}*\n\n`;
    md += `> **Disclaimer:** This log is generated by CareThread, a caregiver communication tool. It is not an official medical record and should be reviewed by a clinician before making health decisions.\n\n`;

    // Observations
    md += `## Observations (Last ${input.daysBack} days)\n`;
    const obs = db.prepare(`
      SELECT o.recorded_at, o.category, o.text, o.severity, m.display_name
      FROM observations o JOIN members m ON o.member_id = m.id
      WHERE o.recorded_at >= ? AND o.circle_id = ?
      ORDER BY o.recorded_at DESC
    `).all(since, ctx.circleId) as any[];
    
    if (obs.length === 0) md += `*None recorded.*\n`;
    for (const o of obs) {
      md += `- **${o.recorded_at.substring(0, 16)}** [${o.category}]: ${o.text} *(logged by ${o.display_name})*\n`;
    }

    // Vitals
    md += `\n## Vitals\n`;
    const vitals = db.prepare(`
      SELECT v.recorded_at, v.kind, v.value, v.unit, m.display_name
      FROM vitals v JOIN members m ON v.member_id = m.id
      WHERE v.recorded_at >= ? AND v.circle_id = ?
      ORDER BY v.recorded_at DESC
    `).all(since, ctx.circleId) as any[];
    
    if (vitals.length === 0) md += `*None recorded.*\n`;
    for (const v of vitals) {
      md += `- **${v.recorded_at.substring(0, 16)}**: ${v.kind} = ${v.value} ${v.unit} *(logged by ${v.display_name})*\n`;
    }

    // Meds
    md += `\n## Medications Given\n`;
    const meds = db.prepare(`
      SELECT e.event_at, med.name, m.display_name
      FROM med_events e 
      JOIN medications med ON e.medication_id = med.id
      JOIN members m ON e.member_id = m.id
      WHERE e.event_at >= ? AND e.status = 'given' AND med.circle_id = ?
      ORDER BY e.event_at DESC
    `).all(since, ctx.circleId) as any[];

    if (meds.length === 0) md += `*None recorded.*\n`;
    for (const m of meds) {
      md += `- **${m.event_at.substring(0, 16)}**: ${m.name} *(by ${m.display_name})*\n`;
    }

    // Audit log
    db.prepare(`INSERT INTO audit_log (id, circle_id, member_id, tool, summary, at) VALUES (?, ?, ?, ?, ?, ?)`).run(
      'aud_'+Date.now(), ctx.circleId, ctx.memberId, 'visit_export', `visit_export: generated markdown`, ctx.now
    );

    return {
      safetyLevel: 'none',
      safetyCode: null,
      spokenText: `I have generated the doctor visit report for the last ${input.daysBack} days.`,
      data: { markdown: md }
    };
  }
});
